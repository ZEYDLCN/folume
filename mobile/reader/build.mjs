// Bundles the reader runtime into one self-contained HTML string (src/reader/readerHtml.generated.ts).
import { build } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(root, '../src/reader/readerHtml.generated.ts');

// The readable fonts travel inside the reader (it runs offline in a WebView): Atkinson Hyperlegible for Latin and Turkish,
// OpenDyslexic for Latin. Both are SIL OFL licensed. The files are only decoded when a paper is set in them.
const fontFile = (pkg, name) => readFileSync(path.join(root, '../node_modules/@fontsource', pkg, 'files', name)).toString('base64');
const face = (family, weight, pkg, file, range) =>
  `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};font-display:swap;src:url(data:font/woff2;base64,${fontFile(pkg, file)}) format('woff2');unicode-range:${range}}`;
const LATIN = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';
const LATIN_EXT = 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF';
const FONT_CSS = [
  face('Atkinson Hyperlegible', 400, 'atkinson-hyperlegible', 'atkinson-hyperlegible-latin-400-normal.woff2', LATIN),
  face('Atkinson Hyperlegible', 400, 'atkinson-hyperlegible', 'atkinson-hyperlegible-latin-ext-400-normal.woff2', LATIN_EXT),
  face('Atkinson Hyperlegible', 700, 'atkinson-hyperlegible', 'atkinson-hyperlegible-latin-700-normal.woff2', LATIN),
  face('Atkinson Hyperlegible', 700, 'atkinson-hyperlegible', 'atkinson-hyperlegible-latin-ext-700-normal.woff2', LATIN_EXT),
  face('OpenDyslexic', 400, 'opendyslexic', 'opendyslexic-latin-400-normal.woff2', LATIN),
].join('\n');

const result = await build({
  entryPoints: [path.join(root, 'src/main.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  target: ['es2020'],
  minify: true,
  alias: { '@': path.join(root, '../src') },
  define: { __FONT_CSS__: JSON.stringify(FONT_CSS) },
  legalComments: 'none',
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html =
  '<!doctype html><html><head><meta charset="utf-8">' +
  '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">' +
  '</head><body><div id="root"></div><script>' + js + '</script></body></html>';
const banner = '/* GENERATED by reader/build.mjs from reader/src. Do not edit; run `npm run build:reader`. */\n';
writeFileSync(out, `${banner}export const READER_HTML: string = ${JSON.stringify(html)};\n`);
mkdirSync(path.join(root, 'dist'), { recursive: true });
writeFileSync(path.join(root, 'dist/reader.html'), html); // used by the e2e checks
console.log(`wrote ${out} (${(html.length / 1024).toFixed(1)} KB)`);
