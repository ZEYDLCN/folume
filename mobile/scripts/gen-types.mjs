// Generates src/core/types.generated.ts from the backend JSON Schema (single source of truth).
import { compile } from 'json-schema-to-typescript';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(fileURLToPath(import.meta.url));

// Pydantic puts a `title` on every property, which json-schema-to-typescript turns into noisy named
// aliases (`Height`, `Kind`, ...). Keep titles only for definitions, and convert `prefixItems`
// (draft 2020-12 tuples) to the draft-07 tuple form the compiler understands.
function clean(node, keepTitle) {
  if (Array.isArray(node)) return node.map((n) => clean(n, false));
  if (node === null || typeof node !== 'object') return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === 'title' && !keepTitle) continue;
    // bounded lists would become huge tuple unions; the limits stay enforced by the schema itself
    if (key === 'maxItems' && !Array.isArray(node.prefixItems)) continue;
    if (key === 'minItems' && !Array.isArray(node.prefixItems)) continue;
    if (key === 'prefixItems') {
      out.items = value.map((v) => clean(v, false));
      continue;
    }
    if (key === '$defs') {
      out[key] = Object.fromEntries(Object.entries(value).map(([name, def]) => [name, clean(def, true)]));
      continue;
    }
    if (key === 'properties') {
      out[key] = Object.fromEntries(Object.entries(value).map(([name, prop]) => [name, clean(prop, false)]));
      continue;
    }
    out[key] = clean(value, false);
  }
  return out;
}

async function generate(schemaFile, rootName, outFile, banner) {
  const schema = clean(JSON.parse(readFileSync(path.join(root, schemaFile), 'utf8')), true);
  const ts = await compile(schema, rootName, {
    bannerComment: banner,
    additionalProperties: false,
    unreachableDefinitions: true,
    style: { singleQuote: true, semi: true, trailingComma: 'all' },
  });
  writeFileSync(path.join(root, outFile), ts);
  console.log('wrote', outFile);
}

const banner = (src) =>
  `/* eslint-disable */\n/**\n * GENERATED by scripts/gen-types.mjs from ${src}.\n * Do not edit; run \`npm run gen:types\`.\n */`;

await generate('../../backend/schema/document.schema.json', 'Document', '../src/core/types.generated.ts', banner('backend/schema/document.schema.json'));
await generate('../../backend/schema/ai.schema.json', 'AiContracts', '../src/ai/types.generated.ts', banner('backend/schema/ai.schema.json'));
