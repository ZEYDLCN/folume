// Generates src/core/types.generated.ts from the backend JSON Schema (single source of truth).
import { compile } from 'json-schema-to-typescript';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(fileURLToPath(import.meta.url));
const schemaPath = path.join(root, '../../backend/schema/document.schema.json');
const target = path.join(root, '../src/core/types.generated.ts');

// Pydantic puts a `title` on every property, which json-schema-to-typescript turns into noisy named
// aliases (`Height`, `Kind`, ...). Keep titles only for definitions, and convert `prefixItems`
// (draft 2020-12 tuples) to the draft-07 tuple form the compiler understands.
function clean(node, keepTitle) {
  if (Array.isArray(node)) return node.map((n) => clean(n, false));
  if (node === null || typeof node !== 'object') return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === 'title' && !keepTitle) continue;
    if (key === 'prefixItems') {
      out.items = value.map((v) => clean(v, false));
      continue;
    }
    if (key === '$defs') {
      out[key] = Object.fromEntries(Object.entries(value).map(([name, def]) => [name, clean(def, true)]));
      continue;
    }
    if (key === 'properties') {
      out[key] = Object.fromEntries(Object.entries(value).map(([name, prop]) => [name, clean(prop, false)]));
      continue;
    }
    out[key] = clean(value, false);
  }
  return out;
}

const schema = clean(JSON.parse(readFileSync(schemaPath, 'utf8')), true);
const ts = await compile(schema, 'Document', {
  bannerComment:
    '/* eslint-disable */\n/**\n * GENERATED by scripts/gen-types.mjs from backend/schema/document.schema.json.\n * Do not edit; run `npm run gen:types`.\n */',
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { singleQuote: true, semi: true, trailingComma: 'all' },
});
writeFileSync(target, ts);
console.log('wrote', target);
